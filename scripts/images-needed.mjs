/*
 * Writes docs/images-needed.md: every image path the data asks for, with its
 * folder, shape, minimum size, what it should show and whether the file is in
 * public/ yet. Run again after changing image paths in src/data:
 *
 *   npm run images:doc
 */
import { existsSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import { createServer } from 'vite'

/** Shape per kind of image. Components pass the same aspect to <SmartImage>. */
const specs = [
  {
    match: /^\/images\/applications\/.+-hero\.jpg$/,
    kind: 'Application hero',
    aspect: '21:9 (shown as a wide band; keep the subject centred)',
    minSize: '2560 × 1100',
  },
  {
    match: /^\/images\/applications\/.+-card\.jpg$/,
    kind: 'Application card',
    aspect: '16:9',
    minSize: '1280 × 720',
  },
  {
    match: /^\/images\/products\//,
    kind: 'Product cut-out (PNG, transparent or white background)',
    aspect: '4:3',
    minSize: '1600 × 1200',
  },
  {
    match: /^\/images\/knowledge\//,
    kind: 'Knowledge card',
    aspect: '3:2',
    minSize: '1200 × 800',
  },
  {
    match: /^\/images\/stories\//,
    kind: 'Customer story card',
    aspect: '4:5 (portrait; headline sits on the lower third)',
    minSize: '1200 × 1500',
  },
  {
    match: /^\/images\/services\//,
    kind: 'Service thumbnail',
    aspect: '4:3',
    minSize: '800 × 600',
  },
]

const server = await createServer({ logLevel: 'error', server: { middlewareMode: true } })
const load = (path) => server.ssrLoadModule(path)
const { applications, rootApplicationId } = await load('/src/data/applications.ts')
const { products } = await load('/src/data/products.ts')
const { services } = await load('/src/data/services.ts')
const { knowledgeItems } = await load('/src/data/knowledge.ts')
await server.close()

const byId = (items) => new Map(items.map((item) => [item.id, item]))
const apps = byId(applications)

// Images seen on the recording path: overview → Municipal water supply → Surface water intake → product.
const root = apps.get(rootApplicationId)
const municipal = apps.get('municipal-water-supply')
const intake = apps.get('surface-water-intake')
const groups = intake.productGroups ?? []
const ahlstar = byId(products).get('ahlstar')
const onRecordingPath = new Set([
  root.heroImage.src,
  ...root.children.map((id) => apps.get(id).cardImage.src),
  municipal.heroImage.src,
  ...municipal.children.map((id) => apps.get(id).cardImage.src),
  intake.heroImage.src,
  ...(intake.knowledgeItemIds ?? []).map((id) => knowledgeItems.find((k) => k.id === id).image.src),
  ...groups.flatMap((g) => g.productIds ?? []).map((id) => byId(products).get(id).images[0].src),
  ...groups.flatMap((g) => g.serviceIds ?? []).map((id) => byId(services).get(id).image.src),
  // The video ends on the AHLSTAR page and scrolls its Explore tab.
  ...(ahlstar.tabs.explore.feature ? [ahlstar.tabs.explore.feature.image.src] : []),
  ...(ahlstar.tabs.explore.storyIds ?? []).map(
    (id) => knowledgeItems.find((k) => k.id === id).image.src,
  ),
])

const images = [
  ...applications.flatMap((app) => [app.heroImage, app.cardImage]),
  ...products.flatMap((product) => [
    ...product.images,
    ...(product.tabs.explore.feature ? [product.tabs.explore.feature.image] : []),
  ]),
  ...knowledgeItems.map((item) => item.image),
  ...services.map((service) => service.image),
]

const rows = images.map(({ src, alt }) => {
  const spec = specs.find((s) => s.match.test(src))
  if (!spec) throw new Error(`No image spec for ${src}`)
  const slash = src.lastIndexOf('/')
  return {
    file: src.slice(slash + 1),
    folder: `public${src.slice(0, slash + 1)}`,
    spec,
    shows: alt,
    priority: onRecordingPath.has(src) ? '1 · recording' : '2',
    present: existsSync(`public${src}`),
  }
})

rows.sort((a, b) => a.priority.localeCompare(b.priority) || a.folder.localeCompare(b.folder))

const missing = rows.filter((row) => !row.present).length
const cell = (text) => text.replaceAll('|', '\\|')

const markdown = `# Images needed

Generated by \`npm run images:doc\` from the image paths in \`src/data\`. Do not edit by hand.

Drop each file into its folder with exactly this name. It shows up on the next page load,
with no code changes. Until then \`<SmartImage>\` shows a blue-to-cyan placeholder labelled
with the file name (hide the labels with \`showPlaceholderLabels\` in \`src/config/demo.ts\`).

- **Sources:** Sulzer media (sulzer.com, media bank, product photography) or licensed stock.
  Never Grundfos images.
- **Priority 1** images are visible on the application finder recording path.
- **Formats:** JPG for photos (quality 80–85), PNG for product cut-outs.

${rows.length} images, ${missing} missing.

| Priority | File | Folder | Aspect | Min. size | Kind | What it should show | Status |
|----------|------|--------|--------|-----------|------|---------------------|--------|
${rows
  .map(
    (r) =>
      `| ${r.priority} | \`${r.file}\` | \`${r.folder}\` | ${r.spec.aspect} | ${r.spec.minSize} | ${r.spec.kind} | ${cell(r.shows)} | ${r.present ? 'present' : 'missing'} |`,
  )
  .join('\n')}
`

await writeFile('docs/images-needed.md', markdown)
console.log(`docs/images-needed.md: ${rows.length} images, ${missing} missing.`)
